"""Generate DNS (Unbound), gateway (nftables) and proxy configuration from the CCC policy state.

    python -m xg_netpolicy.generate --state /var/lib/xephyguard/policy/state.json --out /var/lib/xephyguard/net
    python -m xg_netpolicy.generate --state ... --out ... --watch --apply     # sidecar mode

--apply runs `nft -f <out>/sets.nft` and `unbound-control reload` after every change. Files are
written atomically; a broken state document never replaces a working configuration.
"""
from __future__ import annotations

import argparse
import hashlib
import ipaddress
import json
import logging
import os
import pathlib
import subprocess
import sys
import time

from .state import GROUPS, State

log = logging.getLogger("xg-netpolicy")


def unbound_conf(s: State) -> str:
    """Unbound views: one view per restrictive group; clients are mapped to views by IP.
    Domains of always-blocked categories (DoH resolvers) are blocked for every client."""
    out = [
        "# Generated by XephyGuard (xg_netpolicy). Do not edit; changes are overwritten.",
        f"# state version {s.version}",
        "server:",
        f"    access-control: {s.lab_subnet} allow",
        "    access-control: 127.0.0.0/8 allow",
    ]
    always = sorted(s.blocked_domains_for_group(None).domains)
    for d in always:
        out.append(f'    local-zone: "{d}." always_nxdomain')
    for g in ("test", "block_ai", "isolated"):
        for ip in sorted(s.groups.get(g, [])):
            out.append(f"    access-control-view: {ip}/32 xg_{g}")
    for g in ("test", "block_ai", "isolated"):
        out += ["", "view:", f'    name: "xg_{g}"', "    view-first: yes"]
        if g == "isolated":
            out.append('    local-zone: "." always_refuse')
            continue
        for d in sorted(s.blocked_domains_for_group(g).domains):
            out.append(f'    local-zone: "{d}." always_nxdomain')
    return "\n".join(out) + "\n"


def _set_elements(ips: list[str]) -> str:
    return ", ".join(sorted(set(ips))) if ips else ""


def nft_sets(s: State) -> str:
    """Element updates for the static table installed by ccc-deploy (proxy/nftables/xephyguard.nft)."""
    lines = [f"# Generated by XephyGuard, state version {s.version}"]
    for g in GROUPS:
        name = f"{g}_clients"
        lines.append(f"flush set inet xephyguard {name}")
        el = _set_elements(s.groups.get(g, []))
        if el:
            lines.append(f"add element inet xephyguard {name} {{ {el} }}")
    v4 = [ip for ip in s.doh_ips if isinstance(ipaddress.ip_network(ip, strict=False), ipaddress.IPv4Network)]
    v6 = [ip for ip in s.doh_ips if isinstance(ipaddress.ip_network(ip, strict=False), ipaddress.IPv6Network)]
    lines.append("flush set inet xephyguard resolver_ips")
    if v4:
        lines.append(f"add element inet xephyguard resolver_ips {{ {', '.join(v4)} }}")
    lines.append("flush set inet xephyguard resolver_ips6")
    if v6:
        lines.append(f"add element inet xephyguard resolver_ips6 {{ {', '.join(v6)} }}")
    return "\n".join(lines) + "\n"


def proxy_json(s: State) -> str:
    doc = {
        "version": s.version,
        "groups": s.groups,
        "categories": s.categories,
        "path_rules": s.path_rules,
        "group_categories": s.group_categories,
        "always_block": s.always_block,
        "google": s.google,
        "inspect_hosts": s.inspect_hosts,
        "log_urls": s.log_urls,
        "events_url": s.events_url,
        "events_token": s.events_token,
        "ccc_ip": s.ccc_ip,
        "lab_subnet": s.lab_subnet,
    }
    return json.dumps(doc, indent=1, sort_keys=True) + "\n"


def _write(path: pathlib.Path, text: str) -> bool:
    if path.exists() and path.read_text() == text:
        return False
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text)
    os.chmod(tmp, 0o644)
    tmp.replace(path)
    return True


def generate(state_path: pathlib.Path, out: pathlib.Path) -> dict[str, bool]:
    s = State.load(state_path)
    out.mkdir(parents=True, exist_ok=True)
    return {
        "unbound": _write(out / "unbound-xephyguard.conf", unbound_conf(s)),
        "nft": _write(out / "sets.nft", nft_sets(s)),
        "proxy": _write(out / "proxy.json", proxy_json(s)),
    }


def apply(out: pathlib.Path, changed: dict[str, bool]) -> None:
    if changed.get("nft"):
        r = subprocess.run(["nft", "-f", str(out / "sets.nft")], capture_output=True, text=True)
        if r.returncode:
            log.error("nft failed: %s", r.stderr.strip())
        else:
            log.info("nftables sets updated")
    if changed.get("unbound"):
        r = subprocess.run(["unbound-control", "reload"], capture_output=True, text=True)
        if r.returncode:
            log.error("unbound reload failed: %s", r.stderr.strip() or r.stdout.strip())
        else:
            log.info("unbound reloaded")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--state", required=True, type=pathlib.Path)
    ap.add_argument("--out", required=True, type=pathlib.Path)
    ap.add_argument("--watch", action="store_true")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--interval", type=float, default=1.0)
    a = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    last = None
    while True:
        try:
            digest = hashlib.sha256(a.state.read_bytes()).hexdigest() if a.state.exists() else None
            if digest and digest != last:
                changed = generate(a.state, a.out)
                log.info("state %s -> %s", digest[:12], {k: v for k, v in changed.items() if v} or "no changes")
                if a.apply:
                    apply(a.out, changed)
                last = digest
        except (ValueError, KeyError, json.JSONDecodeError) as e:
            log.error("invalid state document, keeping previous configuration: %s", e)
            last = digest
        if not a.watch:
            return 0
        time.sleep(a.interval)


if __name__ == "__main__":
    sys.exit(main())
